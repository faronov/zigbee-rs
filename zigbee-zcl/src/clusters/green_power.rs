/// Operational role of the Green Power cluster instance.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GpRole {
    /// Router acting as a GP Proxy (client side of the cluster).
    Proxy,
    /// Device acting as a GP Sink (server side of the cluster).
    Sink,
    /// Device implementing both Proxy and Sink.
    Combined,
}

// ---------------------------------------------------------------------------
// Cluster struct
// ---------------------------------------------------------------------------

/// Green Power cluster attribute storage for the GP endpoint (242).
///
/// This holds only the scalar GP attributes that fit the generic ZCL
/// attribute store. GP command processing, the Proxy/Sink tables (long
/// octet strings) and the 24-bit functionality bitmaps are served by the
/// Green Power stack (`zigbee-gp`, wired up by `zigbee-runtime` behind the
/// `green-power` feature), which owns the actual tables and knows which
/// functionality is compiled in. Commands therefore fail with
/// `UnsupClusterCommand` here instead of being silently accepted.
///
/// The attribute set depends on the selected [`GpRole`]:
/// - `Proxy` registers only proxy-side attributes.
/// - `Sink` registers only sink-side attributes.
/// - `Combined` registers both.
pub struct GreenPowerCluster {
    /// Room for every attribute of the `Combined` role.
    store: AttributeStore<16>,
    role: GpRole,
}

impl GreenPowerCluster {
    /// Create the attribute set for `role`. `max_proxy_table_entries` and
    /// `max_sink_table_entries` must report the real table capacities
    /// (ignored for a role without that table).
    pub fn new(role: GpRole, max_proxy_table_entries: u8, max_sink_table_entries: u8) -> Self {
        let mut store = AttributeStore::new();

        if matches!(role, GpRole::Proxy | GpRole::Combined) {
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPP_MAX_PROXY_TABLE_ENTRIES,
                    data_type: ZclDataType::U8,
                    access: AttributeAccess::ReadOnly,
                    name: "gppMaxProxyTableEntries",
                },
                ZclValue::U8(max_proxy_table_entries),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPP_NOTIFICATION_RETRY_NUMBER,
                    data_type: ZclDataType::U8,
                    access: AttributeAccess::ReadWrite,
                    name: "gppNotificationRetryNumber",
                },
                ZclValue::U8(DEFAULT_GPP_NOTIFICATION_RETRY_NUMBER),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPP_NOTIFICATION_RETRY_TIMER,
                    data_type: ZclDataType::U8,
                    access: AttributeAccess::ReadWrite,
                    name: "gppNotificationRetryTimer",
                },
                ZclValue::U8(DEFAULT_GPP_NOTIFICATION_RETRY_TIMER_MS),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPP_MAX_SEARCH_COUNTER,
                    data_type: ZclDataType::U8,
                    access: AttributeAccess::ReadWrite,
                    name: "gppMaxSearchCounter",
                },
                ZclValue::U8(DEFAULT_GPP_MAX_SEARCH_COUNTER),
            );
        }

        if matches!(role, GpRole::Sink | GpRole::Combined) {
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPS_MAX_SINK_TABLE_ENTRIES,
                    data_type: ZclDataType::U8,
                    access: AttributeAccess::ReadOnly,
                    name: "gpsMaxSinkTableEntries",
                },
                ZclValue::U8(max_sink_table_entries),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPS_COMMUNICATION_MODE,
                    data_type: ZclDataType::Bitmap8,
                    access: AttributeAccess::ReadWrite,
                    name: "gpsCommunicationMode",
                },
                ZclValue::Bitmap8(DEFAULT_GPS_COMMUNICATION_MODE),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPS_COMMISSIONING_EXIT_MODE,
                    data_type: ZclDataType::Bitmap8,
                    access: AttributeAccess::ReadWrite,
                    name: "gpsCommissioningExitMode",
                },
                ZclValue::Bitmap8(DEFAULT_GPS_COMMISSIONING_EXIT_MODE),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPS_COMMISSIONING_WINDOW,
                    data_type: ZclDataType::U16,
                    access: AttributeAccess::ReadWrite,
                    name: "gpsCommissioningWindow",
                },
                ZclValue::U16(DEFAULT_GPS_COMMISSIONING_WINDOW_S),
            );
            let _ = store.register(
                AttributeDefinition {
                    id: ATTR_GPS_SECURITY_LEVEL,
                    data_type: ZclDataType::Bitmap8,
                    access: AttributeAccess::ReadWrite,
                    name: "gpsSecurityLevel",
                },
                ZclValue::Bitmap8(DEFAULT_GPS_SECURITY_LEVEL),
            );
        }

        Self { store, role }
    }

    /// The role this instance was created with.
    pub fn role(&self) -> GpRole {
        self.role
    }
}

/// gppNotificationRetryNumber default (A.3.4.2).
pub const DEFAULT_GPP_NOTIFICATION_RETRY_NUMBER: u8 = 2;
/// gppNotificationRetryTimer default, ms (A.3.4.2).
pub const DEFAULT_GPP_NOTIFICATION_RETRY_TIMER_MS: u8 = 100;
/// gppMaxSearchCounter default (A.3.4.2).
pub const DEFAULT_GPP_MAX_SEARCH_COUNTER: u8 = 10;
/// gpsCommunicationMode default: derived groupcast (A.3.3.2.3).
pub const DEFAULT_GPS_COMMUNICATION_MODE: u8 = 0x01;
/// gpsCommissioningExitMode default: on first pairing success (A.3.3.2.4).
pub const DEFAULT_GPS_COMMISSIONING_EXIT_MODE: u8 = 0x02;
/// gpsCommissioningWindow default, s (A.3.3.2.5).
pub const DEFAULT_GPS_COMMISSIONING_WINDOW_S: u16 = 180;
/// gpsSecurityLevel default (A.3.3.2.6).
pub const DEFAULT_GPS_SECURITY_LEVEL: u8 = 0x01;

impl Cluster for GreenPowerCluster {
    fn cluster_id(&self) -> ClusterId {
        ClusterId::GREEN_POWER
    }

    fn handle_command(
        &mut self,
        _cmd_id: CommandId,
        _payload: &[u8],
    ) -> Result<heapless::Vec<u8, 64>, ZclStatus> {
        // GP commands are processed by the Green Power stack on the GP
        // endpoint; this attribute container implements none of them.
        Err(ZclStatus::UnsupClusterCommand)
    }

    fn attributes(&self) -> &dyn AttributeStoreAccess {
        &self.store
    }

    fn attributes_mut(&mut self) -> &mut dyn AttributeStoreMutAccess {
        &mut self.store
    }

    /// Restore the writable configuration attributes. Table capacities are
    /// read-only; pairing tables live in the GP stack and are not touched.
    fn reset_to_factory_defaults(&mut self) {
        if matches!(self.role, GpRole::Proxy | GpRole::Combined) {
            let _ = self.store.set_raw(
                ATTR_GPP_NOTIFICATION_RETRY_NUMBER,
                ZclValue::U8(DEFAULT_GPP_NOTIFICATION_RETRY_NUMBER),
            );
            let _ = self.store.set_raw(
                ATTR_GPP_NOTIFICATION_RETRY_TIMER,
                ZclValue::U8(DEFAULT_GPP_NOTIFICATION_RETRY_TIMER_MS),
            );
            let _ = self.store.set_raw(
                ATTR_GPP_MAX_SEARCH_COUNTER,
                ZclValue::U8(DEFAULT_GPP_MAX_SEARCH_COUNTER),
            );
        }
        if matches!(self.role, GpRole::Sink | GpRole::Combined) {
            let _ = self.store.set_raw(
                ATTR_GPS_COMMUNICATION_MODE,
                ZclValue::Bitmap8(DEFAULT_GPS_COMMUNICATION_MODE),
            );
            let _ = self.store.set_raw(
                ATTR_GPS_COMMISSIONING_EXIT_MODE,
                ZclValue::Bitmap8(DEFAULT_GPS_COMMISSIONING_EXIT_MODE),
            );
            let _ = self.store.set_raw(
                ATTR_GPS_COMMISSIONING_WINDOW,
                ZclValue::U16(DEFAULT_GPS_COMMISSIONING_WINDOW_S),
            );
            let _ = self.store.set_raw(
                ATTR_GPS_SECURITY_LEVEL,
                ZclValue::Bitmap8(DEFAULT_GPS_SECURITY_LEVEL),
            );
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sink_attribute_ids_follow_gp_1_1() {
        let c = GreenPowerCluster::new(GpRole::Sink, 0, 4);
        let a = c.attributes();
        assert_eq!(
            a.get(ATTR_GPS_MAX_SINK_TABLE_ENTRIES),
            Some(&ZclValue::U8(4))
        );
        assert_eq!(a.get(AttributeId(0x0003)), Some(&ZclValue::Bitmap8(0x02)));
        assert_eq!(a.get(AttributeId(0x0004)), Some(&ZclValue::U16(180)));
        assert_eq!(a.get(AttributeId(0x0005)), Some(&ZclValue::Bitmap8(0x01)));
        assert!(a.get(ATTR_GPP_MAX_PROXY_TABLE_ENTRIES).is_none());
    }

    #[test]
    fn combined_role_registers_every_attribute() {
        let c = GreenPowerCluster::new(GpRole::Combined, 8, 4);
        let a = c.attributes();
        for id in [
            ATTR_GPP_MAX_PROXY_TABLE_ENTRIES,
            ATTR_GPP_NOTIFICATION_RETRY_NUMBER,
            ATTR_GPP_NOTIFICATION_RETRY_TIMER,
            ATTR_GPP_MAX_SEARCH_COUNTER,
            ATTR_GPS_MAX_SINK_TABLE_ENTRIES,
            ATTR_GPS_COMMUNICATION_MODE,
            ATTR_GPS_COMMISSIONING_EXIT_MODE,
            ATTR_GPS_COMMISSIONING_WINDOW,
            ATTR_GPS_SECURITY_LEVEL,
        ] {
            assert!(a.get(id).is_some(), "attribute {:#06x} missing", id.0);
        }
    }

    #[test]
    fn proxy_reports_real_capacity_and_rejects_commands() {
        let mut c = GreenPowerCluster::new(GpRole::Proxy, 8, 0);
        assert_eq!(
            c.attributes().get(ATTR_GPP_MAX_PROXY_TABLE_ENTRIES),
            Some(&ZclValue::U8(8))
        );
        assert!(c.attributes().get(ATTR_GPS_SECURITY_LEVEL).is_none());
        assert_eq!(
            c.handle_command(CMD_GP_PAIRING, &[0; 8]),
            Err(ZclStatus::UnsupClusterCommand)
        );
    }
}
