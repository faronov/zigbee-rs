#!/usr/bin/env python3
"""Generate Green Power golden vectors with zigpy (the ZHA GP sink).

The output is pasted into ``zigbee-gp/tests/zigpy_vectors.rs``. It needs a
zigpy checkout that includes ``zigpy.zgp`` (zigpy >= 2.4, as in Home
Assistant 2026.11) plus ``cryptography``::

    python -m venv venv && venv/bin/pip install -e <zigpy> cryptography
    venv/bin/python tools/gp_vectors.py

Every vector is either serialized by zigpy itself (commands the sink sends
or decodes) or encrypted with ``cryptography``'s AES-CCM, so it is
independent of the Rust implementation under test.
"""

from __future__ import annotations

from cryptography.hazmat.primitives.ciphers.aead import AESCCM

import zigpy.types as t
from zigpy.zcl import foundation
from zigpy.zcl.clusters.greenpower import (
    CommissioningNotificationOptions,
    CommissioningNotificationSchema,
    NotificationOptions,
    NotificationSchema,
    PairingOptions,
    PairingSchema,
    ProxyCommissioningModeOptions,
    ProxyCommissioningModeSchema,
    ResponseOptions,
    ResponseSchema,
    TempMasterTxChannel,
)
from zigpy.zgp.commands import (
    GPAttributeReportingPayload,
    GPChannelConfigurationPayload,
    GPChannelRequestPayload,
    GPCommissioningAppInfo,
    GPCommissioningExtendedOptions,
    GPCommissioningOptions,
    GPCommissioningPayload,
    GPCommissioningReplyOptions,
    GPCommissioningReplyPayload,
    GPManufacturerSpecificAttributeReportingPayload,
)
from zigpy.zgp.types import (
    GP_GROUP_ID,
    ApplicationID,
    CommunicationMode,
    GPDCommandID,
    GPDCommandPayload,
    GPPGPDLink,
    ProxyCommissioningModeExitMode,
    SecurityKeyType,
    SecurityLevel,
    SrcID,
)

TCLK = b"ZigBeeAlliance09"
GPD_KEY = bytes(range(0xC0, 0xD0))
SRC_ID = 0x6D6BF300


def emit(name: str, data: bytes) -> None:
    body = ", ".join(f"0x{b:02X}" for b in data)
    print(f"pub const {name}: &[u8] = &[{body}];")


def schema(cls, **kw) -> bytes:
    return cls(**kw).serialize()


def nonce(src_id: int, fc: int, to_gpd: bool = False) -> bytes:
    src = src_id.to_bytes(4, "little")
    return (b"\x00" * 4 if to_gpd else src) + src + fc.to_bytes(4, "little") + b"\x05"


def wrap_key_from_gpd(src_id: int, key: bytes) -> tuple[bytes, bytes]:
    """A.1.5.3.3: TC-LK protection of the GPD key in GPD Commissioning."""
    sealed = AESCCM(TCLK, tag_length=4).encrypt(
        nonce(src_id, src_id), key, src_id.to_bytes(4, "little")
    )
    return sealed[:16], sealed[16:]


def gpdf_l3(src_id: int, fc: int, key: bytes, cmd: int, payload: bytes) -> bytes:
    """Secured (level 3, individual key) GPDF with GPD MAC header, no FCS."""
    nwk = bytes([0x8C, 0x18 | 0x20]) + src_id.to_bytes(4, "little")
    nwk += fc.to_bytes(4, "little")
    sealed = AESCCM(key, tag_length=4).encrypt(
        nonce(src_id, fc), bytes([cmd]) + payload, nwk
    )
    mac = bytes([0x01, 0x08, fc & 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
    return mac + nwk + sealed


def main() -> None:
    print("// @generated by tools/gp_vectors.py from zigpy; do not edit by hand.")
    print("// zigpy dev 64b51efe (zigpy.zgp as shipped with Home Assistant 2026.11 ZHA).")
    print("#![allow(dead_code)]")
    print(f"pub const SRC_ID: u32 = 0x{SRC_ID:08X};")

    # --- GPD → sink payloads (zigpy decodes these) -------------------------
    report = GPAttributeReportingPayload(
        cluster_id=0x0402,
        attributes=[
            foundation.Attribute(
                attrid=0x0000,
                value=foundation.TypeValue(type=0x29, value=t.int16s(2150)),
            )
        ],
    ).serialize()
    emit("ATTR_REPORT_TEMP", report)
    mreport = GPManufacturerSpecificAttributeReportingPayload(
        manufacturer_code=0x6D6B,
        cluster_id=0x0405,
        attributes=[
            foundation.Attribute(
                attrid=0x0000,
                value=foundation.TypeValue(type=0x21, value=t.uint16_t(4875)),
            )
        ],
    ).serialize()
    emit("MFR_ATTR_REPORT_HUMIDITY", mreport)

    wrapped, mic = wrap_key_from_gpd(SRC_ID, GPD_KEY)
    comm = GPCommissioningPayload(
        device_id=0xFE,
        options=GPCommissioningOptions(
            mac_seq_num_capability=1,
            rx_on_capability=0,
            app_info_present=1,
            _reserved=0,
            pan_id_request=0,
            security_key_request=0,
            fixed_location=1,
            extended_options_present=1,
        ),
        extended_options=GPCommissioningExtendedOptions(
            security_level=SecurityLevel.Encrypted,
            key_type=SecurityKeyType.IndividualKey,
            key_present=1,
            key_encrypted=1,
            outgoing_counter_present=1,
        ),
        security_key=t.KeyData(wrapped),
        key_mic=t.uint32_t.deserialize(mic)[0],
        outgoing_counter=t.uint32_t(16),
        app_info=GPCommissioningAppInfo(
            manufacturer_id_present=1,
            model_id_present=1,
            gpd_commands_present=0,
            cluster_list_present=0,
            switch_info_present=0,
            app_description_follows=0,
            _reserved=0,
        ),
        manufacturer_id=t.uint16_t(0x6D6B),
        model_id=t.uint16_t(0xF300),
    ).serialize()
    emit("COMMISSIONING_SENSOR_L3", comm)
    emit("COMMISSIONING_WRAPPED_KEY", wrapped + mic)

    reply = GPCommissioningReplyPayload(
        options=GPCommissioningReplyOptions(
            pan_id_present=0,
            security_key_present=0,
            key_encrypted=0,
            security_level=SecurityLevel.Encrypted,
            key_type=SecurityKeyType.IndividualKey,
        )
    ).serialize()
    emit("COMMISSIONING_REPLY_ZIGPY", reply)
    emit(
        "CHANNEL_REQUEST_15_20",
        GPChannelRequestPayload(next_channel=15 - 11, second_next_channel=20 - 11)
        .serialize(),
    )
    emit(
        "CHANNEL_CONFIGURATION_25",
        GPChannelConfigurationPayload(
            operational_channel=25 - 11, basic=1, _reserved=0
        ).serialize(),
    )

    # --- Proxy → sink commands ---------------------------------------------
    emit(
        "NOTIFICATION_COMM_GROUP_L3",
        schema(
            NotificationSchema,
            options=NotificationOptions(
                application_id=ApplicationID.SrcID,
                also_unicast=0,
                also_derived_group=0,
                also_commissioned_group=1,
                security_level=SecurityLevel.Encrypted,
                security_key_type=SecurityKeyType.IndividualKey,
                rx_after_tx=0,
                tx_queue_full=0,
                bidirectional_cap=0,
                proxy_info_present=0,
                _reserved=0,
            ),
            gpd_id=SrcID(SRC_ID),
            frame_counter=t.uint32_t(0x11),
            command_id=GPDCommandID.AttributeReporting,
            payload=GPDCommandPayload(report),
        ),
    )
    emit(
        "NOTIFICATION_RX_AFTER_TX_PROXY_INFO",
        schema(
            NotificationSchema,
            options=NotificationOptions(
                application_id=ApplicationID.SrcID,
                also_unicast=0,
                also_derived_group=0,
                also_commissioned_group=1,
                security_level=SecurityLevel.Encrypted,
                security_key_type=SecurityKeyType.IndividualKey,
                rx_after_tx=1,
                tx_queue_full=0,
                bidirectional_cap=1,
                proxy_info_present=1,
                _reserved=0,
            ),
            gpd_id=SrcID(SRC_ID),
            frame_counter=t.uint32_t(0x12),
            command_id=GPDCommandID.Toggle,
            payload=GPDCommandPayload(b""),
            gpp_short_addr=t.uint16_t(0x1234),
            gpp_gpd_link=GPPGPDLink(rssi=40, link_quality=3),
        ),
    )
    emit(
        "COMMISSIONING_NOTIFICATION_PROXY_INFO",
        schema(
            CommissioningNotificationSchema,
            options=CommissioningNotificationOptions(
                application_id=ApplicationID.SrcID,
                rx_after_tx=0,
                security_level=SecurityLevel.NoSecurity,
                security_key_type=SecurityKeyType.NoKey,
                security_failed=0,
                bidirectional_cap=0,
                proxy_info_present=1,
                _reserved=0,
            ),
            gpd_id=SrcID(SRC_ID),
            frame_counter=t.uint32_t(0x05),
            command_id=GPDCommandID.CommissioningRequest,
            payload=GPDCommandPayload(comm),
            gpp_short_addr=t.uint16_t(0x1234),
            gpp_gpd_link=GPPGPDLink(rssi=40, link_quality=3),
        ),
    )
    emit(
        "COMMISSIONING_NOTIFICATION_SECURITY_FAILED",
        schema(
            CommissioningNotificationSchema,
            options=CommissioningNotificationOptions(
                application_id=ApplicationID.SrcID,
                rx_after_tx=0,
                security_level=SecurityLevel.Encrypted,
                security_key_type=SecurityKeyType.IndividualKey,
                security_failed=1,
                bidirectional_cap=0,
                proxy_info_present=1,
                _reserved=0,
            ),
            gpd_id=SrcID(SRC_ID),
            frame_counter=t.uint32_t(0x20),
            command_id=GPDCommandID(0x5A),
            payload=GPDCommandPayload(b"\x01\x02"),
            gpp_short_addr=t.uint16_t(0x1234),
            gpp_gpd_link=GPPGPDLink(rssi=10, link_quality=1),
            mic=t.uint32_t(0xA1B2C3D4),
        ),
    )

    # --- Sink → proxy commands, exactly as zigpy's GreenPowerManager -------
    emit(
        "PCM_ENTER_180",
        schema(
            ProxyCommissioningModeSchema,
            options=ProxyCommissioningModeOptions(
                enter=1,
                commissioning_window_present=1,
                exit_mode=ProxyCommissioningModeExitMode.OnExplicitExit,
                channel_present=0,
                unicast=0,
                _reserved=0,
            ),
            window=t.uint16_t(180),
        ),
    )
    emit(
        "PCM_EXIT",
        schema(
            ProxyCommissioningModeSchema,
            options=ProxyCommissioningModeOptions(
                enter=0,
                commissioning_window_present=0,
                exit_mode=ProxyCommissioningModeExitMode.OnExplicitExit,
                channel_present=0,
                unicast=0,
                _reserved=0,
            ),
            window=None,
        ),
    )
    pairing_opts = dict(
        application_id=ApplicationID.SrcID,
        communication_mode=CommunicationMode.GroupcastForwardToCommGroup,
        gpd_fixed=1,
        gpd_mac_seq_num_cap=1,
        security_level=SecurityLevel.Encrypted,
        security_key_type=SecurityKeyType.IndividualKey,
        assigned_alias_present=0,
        groupcast_radius_present=0,
        _reserved=0,
    )
    emit(
        "PAIRING_ADD_L3",
        schema(
            PairingSchema,
            options=PairingOptions(
                add_sink=1,
                remove_gpd=0,
                security_frame_counter_present=1,
                security_key_present=1,
                **pairing_opts,
            ),
            gpd_id=SrcID(SRC_ID),
            sink_group=GP_GROUP_ID,
            device_id=t.uint8_t(0xFE),
            frame_counter=t.uint32_t(16),
            key=t.KeyData(GPD_KEY),
        ),
    )
    emit(
        "PAIRING_REMOVE",
        schema(
            PairingSchema,
            options=PairingOptions(
                add_sink=0,
                remove_gpd=1,
                security_frame_counter_present=0,
                security_key_present=0,
                **pairing_opts,
            ),
            gpd_id=SrcID(SRC_ID),
        ),
    )
    emit(
        "RESPONSE_CHANNEL_CONFIGURATION",
        schema(
            ResponseSchema,
            options=ResponseOptions(
                application_id=ApplicationID.SrcID,
                transmit_on_endpoint_match=0,
                _reserved=0,
            ),
            temp_master_short_addr=t.uint16_t(0x1234),
            temp_master_tx_channel=TempMasterTxChannel(
                transmit_channel=t.uint4_t(15 - 11), _reserved=0
            ),
            gpd_id=SrcID(0),
            gpd_command_id=GPDCommandID.ChannelConfiguration,
            gpd_command_payload=t.LVBytes(
                GPChannelConfigurationPayload(
                    operational_channel=25 - 11, basic=1, _reserved=0
                ).serialize()
            ),
        ),
    )
    emit(
        "RESPONSE_COMMISSIONING_REPLY",
        schema(
            ResponseSchema,
            options=ResponseOptions(
                application_id=ApplicationID.SrcID,
                transmit_on_endpoint_match=0,
                _reserved=0,
            ),
            temp_master_short_addr=t.uint16_t(0x1234),
            temp_master_tx_channel=TempMasterTxChannel(
                transmit_channel=t.uint4_t(25 - 11), _reserved=0
            ),
            gpd_id=SrcID(SRC_ID),
            gpd_command_id=GPDCommandID.CommissioningReply,
            gpd_command_payload=t.LVBytes(reply),
        ),
    )

    # --- Over-the-air GPDF (independent AES-CCM) ---------------------------
    emit("GPDF_L3_TEMP_REPORT", gpdf_l3(SRC_ID, 0x11, GPD_KEY, 0xA0, report))


if __name__ == "__main__":
    main()
