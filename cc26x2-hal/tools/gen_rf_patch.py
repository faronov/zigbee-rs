#!/usr/bin/env python3
"""Generate `src/rf/patch_ieee.rs` from the vendored TI CPE patch.

Input: `vendor/ti/rf_patches/rf_patch_cpe_ieee_802_15_4.c` (SimpleLink Low
Power F2 SDK 8.33.00.16, BSD-3-Clause; byte-identical in the
`cc13x2_cc26x2` and `cc13x2x7_cc26x2x7` device trees). The generator copies
the patch image words, the RF core RAM offsets and the patch-table writes of
`configureIeee802154Patch()` verbatim; it fails on any construct it does not
understand (CPEHD/SYS patch words, other table writes) instead of guessing.

    python3 tools/gen_rf_patch.py          # rewrite
    python3 tools/gen_rf_patch.py --check  # CI: fail if out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "vendor/ti/rf_patches/rf_patch_cpe_ieee_802_15_4.c"
OUT = ROOT / "src/rf/patch_ieee.rs"


def parse(text):
    image = re.search(r"patchImageIeee802154\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not image:
        sys.exit("patch image array not found")
    words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]{8}", image.group(1))]

    def define(name):
        m = re.search(r"#define\s+%s\s+(0x[0-9A-Fa-f]+|\d+)" % name, text)
        if not m:
            sys.exit("missing #define " + name)
        return int(m.group(1), 0)

    n = define("_NWORD_PATCHIMAGE_IEEE_802_15_4")
    if n != len(words):
        sys.exit("word count %d != _NWORD_PATCHIMAGE %d" % (len(words), n))
    if define("_NWORD_PATCHCPEHD_IEEE_802_15_4") != 0:
        sys.exit("CPEHD patch words are not supported by this generator")
    if define("_NWORD_PATCHSYS_IEEE_802_15_4") != 0:
        sys.exit("SYS patch words are not supported by this generator")
    cfg = re.search(r"configureIeee802154Patch\(void\)\s*\{(.*?)\}", text, re.S)
    if not cfg:
        sys.exit("configureIeee802154Patch not found")
    body = cfg.group(1)
    writes = re.findall(r"pPatchTab\[(\d+)\]\s*=\s*(\d+);", body)
    stray = re.sub(r"uint8_t \*pPatchTab = .*?;|pPatchTab\[\d+\]\s*=\s*\d+;|\s", "", body)
    if stray:
        sys.exit("unexpected statements in configureIeee802154Patch: " + stray)
    return {
        "words": words,
        "cperam": define("_IEEE_802_15_4_CPERAM_START"),
        "vec": define("_IEEE_802_15_4_PATCH_VEC_OFFSET"),
        "tab": define("_IEEE_802_15_4_PATCH_TAB_OFFSET"),
        "writes": [(int(i), int(v)) for i, v in writes],
    }


def render(p):
    lines = [
        "//! IEEE 802.15.4 CPE patch for the CC13x2/CC26x2 RF core.",
        "//!",
        "//! @generated by `tools/gen_rf_patch.py` from",
        "//! `vendor/ti/rf_patches/rf_patch_cpe_ieee_802_15_4.c` (TI SimpleLink Low",
        "//! Power F2 SDK 8.33.00.16, Copyright (c) 2015-2022 Texas Instruments",
        "//! Incorporated, BSD-3-Clause; the license text is in that file). The same",
        "//! file ships for `cc13x2_cc26x2` and `cc13x2x7_cc26x2x7`. Do not edit.",
        "",
        "/// RF core RAM base (`_IEEE_802_15_4_CPERAM_START`).",
        "pub const CPERAM_START: u32 = 0x%08X;" % p["cperam"],
        "/// Patch vector offset in RF core RAM (`_IEEE_802_15_4_PATCH_VEC_OFFSET`).",
        "pub const PATCH_VEC_OFFSET: u32 = 0x%04X;" % p["vec"],
        "/// Patch table offset in RF core RAM (`_IEEE_802_15_4_PATCH_TAB_OFFSET`).",
        "pub const PATCH_TAB_OFFSET: u32 = 0x%04X;" % p["tab"],
        "",
        "/// `configureIeee802154Patch()`: `(byte index, value)` writes to the patch table.",
        "pub const PATCH_TAB_WRITES: [(u16, u8); %d] = [" % len(p["writes"]),
    ]
    lines += ["    (%d, %d)," % w for w in p["writes"]]
    lines += [
        "];",
        "",
        "/// `patchImageIeee802154[]`, copied to `CPERAM_START + PATCH_VEC_OFFSET`.",
        "pub static PATCH_IMAGE: [u32; %d] = [" % len(p["words"]),
    ]
    lines += ["    0x%08x," % w for w in p["words"]]
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    out = render(parse(SRC.read_text()))
    if "--check" in sys.argv:
        if OUT.read_text() != out:
            sys.exit("%s is out of date; run tools/gen_rf_patch.py" % OUT)
        return
    OUT.write_text(out)


if __name__ == "__main__":
    main()
