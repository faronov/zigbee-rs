//! Loader-linked (`zrs-boot`) ZBT-1 images: the layout the image is linked
//! for, its signing identity and the trial confirm.
//!
//! The resident Gecko Bootloader (`0x0..0x4000`, never written) starts the
//! zigbee-rs loader at `0x4000` (`bootloaders/efr32s2-boot`, deployment
//! `ha-connect-zbt1`, [`boot/zbt1.layout`](layout)). The loader installs a
//! signed image staged in the secondary slot by overwriting the primary
//! slot, then starts it on trial. This image has no Zigbee OTA client:
//! upgrades are staged over SWD. It confirms itself with one write into the
//! primary slot's trial log once the router is back on the network
//! ([`TrialConfirm`]). The overwrite loader cannot revert, so an
//! unconfirmed image keeps running and the loader only reports it.
//!
//! The Green Power Proxy Table journal (`0xF0000..0xF4000`), the router
//! tables (`0xF4000..0xFC000`) and the security journal (`0xFC000..`) keep
//! the addresses of the direct map (`link/memory.x`), so a direct-linked
//! router and a loader-linked one resume the same network state, GP Proxy
//! Table and frame counters. Loader-version 1 layouts ended the secondary
//! slot at `0xF4000`, over the GP window; version 2 ends both slots below it.
//!
//! # Identity
//!
//! `tools/zrs_boot_ota.py` reads [`OTA_IDENTITY`] from the ELF (symbol
//! `ZRS_OTA_IDENTITY`) to sign the image as `MM.mm.pp+0`, the version the
//! loader's downgrade prevention compares. The Zigbee file version is
//! `0x25MMmmpp`, as for the other zigbee-rs loader products.

use efr32s2_hal::flash::{Efr32s2Flash, FlashPartition};
use embedded_storage::nor_flash::{NorFlash, NorFlashError, ReadNorFlash};
pub use mcuboot_image::{BootError, TrialState};
use mcuboot_image::{LoaderChannel, Mode, StagingFlash};

/// Constants of the loader layout (`boot/zbt1.layout`) the image is linked
/// for, generated by `build.rs`.
pub mod layout {
    include!(concat!(env!("OUT_DIR"), "/boot_layout.rs"));
}

use layout::{
    JOURNAL_END, JOURNAL_START, LOADER_INFO_ADDR, LOADER_START, MCUBOOT, PRIMARY_SLOT, RESERVED,
    SECONDARY_SLOT, SLOT_SIZE, TRUSTED_KEYS,
};

// The loader layout keeps the direct map's persistence: the security
// journal and, reserved, the GP Proxy Table journal, the router tables and
// the Gecko Bootloader.
const _: () = assert!(JOURNAL_START == crate::PERSISTENCE_PARTITION_START);
const _: () = assert!(JOURNAL_END == crate::PERSISTENCE_PARTITION_END);
const _: () = assert!(reserves(0, crate::APPLICATION_START));
const _: () = assert!(reserves(
    crate::CHILD_TABLE_PARTITION_START,
    crate::PERSISTENCE_PARTITION_START
));
const _: () = assert!(reserves(
    crate::GP_PROXY_TABLE_PARTITION_START,
    crate::CHILD_TABLE_PARTITION_START
));
// Gecko starts whatever is at the direct map's application start: the
// loader lives there, and both slots end below the GP Proxy Table journal.
const _: () = assert!(LOADER_START == crate::APPLICATION_START);
const _: () = assert!(PRIMARY_SLOT + SLOT_SIZE <= BELOW_PERSISTENCE as u32);
const _: () = assert!(SECONDARY_SLOT + SLOT_SIZE <= BELOW_PERSISTENCE as u32);
const _: () = assert!(LOADER_INFO_ADDR < PRIMARY_SLOT);

/// Whether the layout reserves exactly `[start, end)`.
const fn reserves(start: u32, end: u32) -> bool {
    let mut index = 0;
    while index < RESERVED.len() {
        let (_, from, to) = RESERVED[index];
        if from == start && to == end {
            return true;
        }
        index += 1;
    }
    false
}

/// zigbee-rs development manufacturer code (as the other zigbee-rs
/// products). Not a Zigbee Alliance assignment.
pub const MANUFACTURER_CODE: u16 = 0x1234;
/// ZBT-1 router image type. Distinct from the other zigbee-rs products
/// (EFR32 TRADFRI `0x0002`, ESP32 `0x0001`/`0x0002`, BL702 `0x0702`,
/// flower `0x2340`..`0x2342`, EFR32MG22 `0x0022`).
pub const IMAGE_TYPE: u16 = 0x2101;
/// Most significant byte of every file version of this firmware.
pub const FILE_VERSION_PREFIX: u8 = 0x25;

/// `0x25MMmmpp`.
pub const fn file_version(major: u8, minor: u8, patch: u8) -> u32 {
    (FILE_VERSION_PREFIX as u32) << 24 | (major as u32) << 16 | (minor as u32) << 8 | patch as u32
}

/// This build's file version.
pub const FILE_VERSION: u32 = file_version(crate::VERSION.0, crate::VERSION.1, crate::VERSION.2);

/// Identity record for `tools/zrs_boot_ota.py` (symbol `ZRS_OTA_IDENTITY`):
/// `[manufacturer | image type << 16, file version]`.
pub const OTA_IDENTITY: [u32; 2] = [
    MANUFACTURER_CODE as u32 | (IMAGE_TYPE as u32) << 16,
    FILE_VERSION,
];

/// First byte of the router persistence (the GP Proxy Table journal, then
/// the router tables and the security journal): the slots, the loader and
/// the Gecko Bootloader lie below it.
pub const BELOW_PERSISTENCE: usize = crate::GP_PROXY_TABLE_PARTITION_START as usize;

/// Internal flash below the router persistence (absolute addresses).
pub type LowFlash = FlashPartition<0, BELOW_PERSISTENCE>;

/// The confirm's flash view: [`LowFlash`] bounded by [`StagingFlash`], which
/// admits writes only into the secondary slot and the running image's
/// trial log and refuses the Gecko Bootloader, the loader and the running
/// image. [`TrialConfirm`] writes only the trial log.
pub type BootFlash = StagingFlash<LowFlash>;

/// Split the unique internal-flash handle into the loader view (below the
/// router persistence) and the handle for [`crate::router::router_stores`],
/// the GP Proxy Table store and [`crate::storage::security_store`], whose
/// partitions start at the GP window.
pub fn split_flash(flash: Efr32s2Flash) -> (Efr32s2Flash, BootFlash) {
    // SAFETY: `LowFlash` ends where the GP window begins (asserted above),
    // the returned handle is only used through the GP, router-table and
    // security-journal partitions above it, and this function consumes the
    // only safe handle before minting the window. Flash is used from one
    // executor; no interrupt handler issues MSC operations.
    let low = unsafe { LowFlash::new_unchecked() };
    (flash, StagingFlash::new(low, MCUBOOT))
}

/// Which loader starts this image.
pub fn channel<F: ReadNorFlash>(flash: &mut F) -> LoaderChannel {
    LoaderChannel::read(flash, LOADER_INFO_ADDR, &TRUSTED_KEYS)
}

/// One confirm per boot for an image the loader started on trial.
pub struct TrialConfirm<F> {
    flash: F,
    state: Result<TrialState, BootError>,
    attempted: bool,
}

impl<F: NorFlash> TrialConfirm<F>
where
    F::Error: NorFlashError,
{
    /// Read the running image's trial state.
    pub fn new(mut flash: F) -> Self {
        let state = mcuboot_image::trial_state(&mut flash, &MCUBOOT, Mode::Overwrite);
        Self {
            flash,
            state,
            attempted: false,
        }
    }

    /// The trial state read at boot (or after the confirm).
    pub fn state(&self) -> Result<TrialState, BootError> {
        self.state
    }

    /// Whether the image is on trial and has not tried to confirm yet.
    pub fn pending(&self) -> bool {
        !self.attempted && matches!(self.state, Ok(TrialState::Testing { .. }))
    }

    /// Append the confirm record. Called once the router is back on the
    /// network; at most one attempt per boot, so a failing flash is not
    /// retried in a loop (the next boot tries again). Returns the state
    /// before the confirm.
    pub fn confirm(&mut self) -> Result<TrialState, BootError> {
        self.attempted = true;
        let before = mcuboot_image::confirm(&mut self.flash, &MCUBOOT, Mode::Overwrite);
        if before.is_ok() {
            self.state = Ok(TrialState::Confirmed);
        }
        before
    }

    /// The flash view.
    pub fn flash_mut(&mut self) -> &mut F {
        &mut self.flash
    }
}

/// The confirm is due once the router is online and has decrypted at least
/// one NWK-secured frame since boot: its network key and frame counters
/// work on the air, not only in the restored journal.
pub const fn confirm_due(online: bool, secured_frames_decrypted: u32) -> bool {
    online && secured_frames_decrypted > 0
}

#[cfg(test)]
mod tests {
    extern crate std;

    use super::*;
    use embedded_storage::nor_flash::{ErrorType, NorFlashErrorKind};
    use mcuboot_image::{BOOT_MAGIC, BootConfig, Trial, TrustedKey, Update, trial_log_area};
    use std::vec::Vec;

    // Shared imgtool vectors: header 0x100, TEST-ONLY key.
    const TEST_KEY_XY: &[u8; 64] =
        include_bytes!("../../../mcuboot-image/tests/vectors/test-key.xy");
    const TEST_V1: &[u8] = include_bytes!("../../../mcuboot-image/tests/vectors/test-v1.bin");
    const TEST_V2: &[u8] = include_bytes!("../../../mcuboot-image/tests/vectors/test-v2.bin");

    static TEST_KEYS: [TrustedKey; 1] = [TrustedKey::new(*TEST_KEY_XY)];

    /// Flash below the router persistence with the EFR32 geometry (8 KiB pages,
    /// 4-byte writes that only clear bits) and a write log.
    struct MockFlash {
        bytes: Vec<u8>,
        writes: Vec<(u32, usize)>,
        fail_writes: bool,
    }

    impl MockFlash {
        /// `running` in the primary slot, `staged` (padded, with the
        /// request magic) in the secondary.
        fn new(running: &[u8], staged: Option<&[u8]>) -> Self {
            let mut bytes = std::vec![0xFF; BELOW_PERSISTENCE];
            let primary = PRIMARY_SLOT as usize;
            bytes[primary..primary + running.len()].copy_from_slice(running);
            if let Some(image) = staged {
                let secondary = SECONDARY_SLOT as usize;
                bytes[secondary..secondary + image.len()].copy_from_slice(image);
                let magic = secondary + SLOT_SIZE as usize - BOOT_MAGIC.len();
                bytes[magic..magic + BOOT_MAGIC.len()].copy_from_slice(&BOOT_MAGIC);
            }
            Self {
                bytes,
                writes: Vec::new(),
                fail_writes: false,
            }
        }

        fn range(
            &self,
            from: u32,
            len: usize,
        ) -> Result<core::ops::Range<usize>, NorFlashErrorKind> {
            let start = from as usize;
            start
                .checked_add(len)
                .filter(|end| *end <= self.bytes.len())
                .map(|end| start..end)
                .ok_or(NorFlashErrorKind::OutOfBounds)
        }
    }

    impl ErrorType for MockFlash {
        type Error = NorFlashErrorKind;
    }

    impl ReadNorFlash for MockFlash {
        const READ_SIZE: usize = 1;

        fn read(&mut self, offset: u32, bytes: &mut [u8]) -> Result<(), Self::Error> {
            let range = self.range(offset, bytes.len())?;
            bytes.copy_from_slice(&self.bytes[range]);
            Ok(())
        }

        fn capacity(&self) -> usize {
            self.bytes.len()
        }
    }

    impl NorFlash for MockFlash {
        const WRITE_SIZE: usize = 4;
        const ERASE_SIZE: usize = 0x2000;

        fn erase(&mut self, from: u32, to: u32) -> Result<(), Self::Error> {
            if !from.is_multiple_of(0x2000) || !to.is_multiple_of(0x2000) || from > to {
                return Err(NorFlashErrorKind::NotAligned);
            }
            let range = self.range(from, (to - from) as usize)?;
            self.bytes[range].fill(0xFF);
            Ok(())
        }

        fn write(&mut self, offset: u32, bytes: &[u8]) -> Result<(), Self::Error> {
            if self.fail_writes {
                return Err(NorFlashErrorKind::Other);
            }
            if !offset.is_multiple_of(4) || !bytes.len().is_multiple_of(4) {
                return Err(NorFlashErrorKind::NotAligned);
            }
            let range = self.range(offset, bytes.len())?;
            self.writes.push((offset, bytes.len()));
            for (old, new) in self.bytes[range].iter_mut().zip(bytes) {
                *old &= *new;
            }
            Ok(())
        }
    }

    fn config() -> BootConfig<'static> {
        BootConfig {
            keys: &TEST_KEYS,
            ..layout::BOOT_CONFIG
        }
    }

    /// What the loader leaves after installing a staged upgrade and
    /// starting it `boots` times.
    fn on_trial(boots: u16) -> MockFlash {
        let mut flash = MockFlash::new(TEST_V1, Some(TEST_V2));
        for boot in 1..=boots {
            let booted = mcuboot_image::boot(&mut flash, &config(), |_| {}).unwrap();
            assert_eq!(booted.trial, Trial::Testing { boot });
            if boot == 1 {
                assert_eq!(booted.update, Update::Installed);
            }
        }
        flash.writes.clear();
        flash
    }

    #[test]
    fn layout_keeps_gecko_and_the_direct_map_persistence() {
        assert_eq!(LOADER_START, 0x4000);
        assert_eq!(
            (JOURNAL_START, JOURNAL_END),
            (
                crate::PERSISTENCE_PARTITION_START,
                crate::PERSISTENCE_PARTITION_END
            )
        );
        assert!(reserves(0, 0x4000), "Gecko Bootloader reserved");
        assert!(reserves(0xF4000, 0xFC000), "router tables reserved");
    }

    #[test]
    fn file_version_and_identity() {
        assert_eq!(file_version(0, 2, 1), 0x2500_0201);
        assert_eq!(OTA_IDENTITY[0], 0x2101_1234);
        assert_eq!(OTA_IDENTITY[1] >> 24, 0x25);
        assert_eq!(OTA_IDENTITY[1], FILE_VERSION);
    }

    #[test]
    fn confirm_is_due_only_online_with_secured_traffic() {
        assert!(!confirm_due(false, 5));
        assert!(!confirm_due(true, 0));
        assert!(confirm_due(true, 1));
    }

    #[test]
    fn a_permanent_image_is_never_written() {
        let mut flash = MockFlash::new(TEST_V1, None);
        {
            let mut trial = TrialConfirm::new(StagingFlash::new(&mut flash, MCUBOOT));
            assert_eq!(trial.state(), Ok(TrialState::Permanent));
            assert!(!trial.pending());
            assert_eq!(trial.confirm(), Ok(TrialState::Permanent));
        }
        assert!(flash.writes.is_empty());
    }

    #[test]
    fn an_image_on_trial_confirms_once_into_the_trial_log() {
        let mut flash = on_trial(2);
        let before = flash.bytes.clone();
        {
            let mut trial = TrialConfirm::new(StagingFlash::new(&mut flash, MCUBOOT));
            assert_eq!(trial.state(), Ok(TrialState::Testing { attempts: 2 }));
            assert!(trial.pending());
            assert_eq!(trial.confirm(), Ok(TrialState::Testing { attempts: 2 }));
            assert!(!trial.pending());
            assert_eq!(trial.state(), Ok(TrialState::Confirmed));
        }
        let (log_start, log_end) = trial_log_area(&MCUBOOT);
        assert_eq!(flash.writes.len(), 1);
        let (offset, len) = flash.writes[0];
        assert!(log_start <= offset && offset + len as u32 <= log_end);
        let (start, end) = (log_start as usize, log_end as usize);
        assert!(flash.bytes[..start] == before[..start]);
        assert!(flash.bytes[end..] == before[end..]);
        // The next boot finds it confirmed; the confirm writes nothing.
        let booted = mcuboot_image::boot(&mut flash, &config(), |_| {}).unwrap();
        assert_eq!(booted.trial, Trial::Confirmed);
        flash.writes.clear();
        {
            let mut again = TrialConfirm::new(StagingFlash::new(&mut flash, MCUBOOT));
            assert_eq!(again.state(), Ok(TrialState::Confirmed));
            assert!(!again.pending());
            assert_eq!(again.confirm(), Ok(TrialState::Confirmed));
        }
        assert!(flash.writes.is_empty());
    }

    #[test]
    fn a_failed_confirm_is_not_retried_this_boot() {
        let mut flash = on_trial(1);
        flash.fail_writes = true;
        let mut trial = TrialConfirm::new(StagingFlash::new(&mut flash, MCUBOOT));
        assert!(trial.confirm().is_err());
        assert!(!trial.pending());
        assert_eq!(trial.state(), Ok(TrialState::Testing { attempts: 1 }));
    }

    #[test]
    fn the_view_refuses_gecko_the_loader_and_the_running_image() {
        let mut flash = MockFlash::new(TEST_V1, None);
        let before = flash.bytes.clone();
        {
            let mut view = StagingFlash::new(&mut flash, MCUBOOT);
            let word = [0u8; 4];
            for address in [
                0x0,
                0x3FFC,
                LOADER_START,
                LOADER_INFO_ADDR,
                PRIMARY_SLOT,
                PRIMARY_SLOT + 0x1000,
            ] {
                assert!(view.write(address, &word).is_err(), "{address:#X}");
            }
            for from in [0x0, LOADER_START, PRIMARY_SLOT] {
                assert!(view.erase(from, from + 0x2000).is_err(), "{from:#X}");
            }
            // The GP window, the router tables and the journal lie outside
            // the view.
            assert!(view.write(BELOW_PERSISTENCE as u32, &word).is_err());
            assert!(view.write(crate::CHILD_TABLE_PARTITION_START, &word).is_err());
            let mut byte = [0];
            assert!(view.read(JOURNAL_START, &mut byte).is_err());
        }
        assert!(flash.bytes == before);
        assert!(flash.writes.is_empty());
    }
}
